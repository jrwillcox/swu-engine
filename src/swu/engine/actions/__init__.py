"""Actions: every decision a player can make, and the legal_actions/apply contract.

EVERY decision in a SWU game - from the opening mulligan to the final attack - is
an :class:`~swu.engine.actions.base.Action`.  The engine loop is simply::

    while not state.is_terminal():
        acts = legal_actions(state)
        chosen = player.choose_action(view, acts)
        state = apply(state, chosen)

Key invariants:

* ``legal_actions()`` is never empty while the game is live.
* ``apply()`` raises ``IllegalActionError`` when the action is not legal.
* ``apply()`` never mutates its input (deep-copy-then-modify).
* All randomness uses ``state.make_rng()``, which advances the embedded RNG; the
  new state's ``rng_state`` reflects the post-shuffle RNG position.
* When ``pending_decisions`` is non-empty, ``legal_actions()`` returns only the
  top decision's options; turn alternation is suspended.

This package was one 24,788-line module.  It is now a layered kernel plus one
module per decision family, and **this file is its declared public surface** -
the ``__all__`` the single module never had.  Every name below is imported
somewhere in the tree (3,532 sites in 89 files), so re-exporting them is a
compatibility contract, not a convenience: ``from swu.engine.actions import X``
keeps working for every X it ever worked for.  ``tests/test_actions_contract.py``
pins that, including two observers reachable only by attribute access.

Import submodules directly (``from swu.engine.actions.stats import compute_power``)
in new code; the flat re-exports exist for the call sites that predate the split.
"""

